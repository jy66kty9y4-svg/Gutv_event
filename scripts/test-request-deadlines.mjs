import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';
import ts from 'typescript';
import { validFilmingDate } from '../app/filming-validation.ts';
const exports = {};
const source = ts.transpileModule(readFileSync(new URL('../app/request-deadlines.ts', import.meta.url), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
runInNewContext(source, { exports, require: () => ({ validFilmingDate }), Date });
const { requestDeadlineWarnings: warnings } = exports;
const brief = (requestKind, date, deliveryDate = '') => ({ requestKind, deliveryDate, slots: [{ startsAt: date + 'T12:00', endsAt: date + 'T13:00', location: 'Студия' }] });
assert.equal(warnings(brief('event', '2026-09-21'), '2026-09-07 10:00:00').length, 0, '14 days inclusive');
assert.equal(warnings(brief('event', '2026-09-20'), '2026-09-07 10:00:00').length, 1, '13 days flagged');
assert.equal(warnings(brief('event', '2026-09-21'), '2026-09-07 21:00:00').length, 1, 'Moscow submission day, UTC midnight boundary');
assert.equal(warnings(brief('video', '2026-09-08', '2026-09-28'), '2026-09-07 10:00:00').length, 0, '21 days uses delivery, not filming');
assert.equal(warnings(brief('video', '2026-09-08', '2026-09-27'), '2026-09-07 10:00:00').length, 1);
assert.equal(warnings(brief('event_video', '2026-09-08', '2026-09-09'), '2026-09-07 10:00:00').length, 2, 'Both deadlines apply');
assert.equal(warnings(brief('trip', '2026-11-07'), '2026-09-07 10:00:00').length, 0, 'Two calendar months inclusive');
assert.equal(warnings(brief('trip', '2026-11-06'), '2026-09-07 10:00:00').length, 1);
assert.equal(warnings(brief('trip', '2026-04-30'), '2026-02-28 10:00:00').length, 0, 'Month end clamped');
assert.equal(warnings(brief('trip', '2024-04-30'), '2024-02-29 10:00:00').length, 0, 'Leap year clamped');
assert.equal(warnings(brief('video', '2026-09-10'), '2026-09-07 10:00:00').length, 0, 'Removed delivery field does not require an exception');
assert.equal(warnings(null, '2026-09-07 10:00:00').length, 1, 'Legacy type requires manual review');
assert.equal(warnings({ ...brief('event', '2026-10-30'), slots: [...brief('event', '2026-10-30').slots, ...brief('event', '2026-09-08').slots] }, '2026-09-07 10:00:00').length, 1, 'Earliest interval, regardless of order');
console.log('PASS rule deadlines: event, video, mixed, trip, calendar boundaries, Moscow, legacy, multiple intervals');
